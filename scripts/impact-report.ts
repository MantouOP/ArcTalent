/** Prints the Phase 2 impact benchmark as Markdown: `npm run impact > docs/IMPACT.md`. */
import { baseline, employees } from '../src/lib/catalogue';
import { MODEL_VERSION } from '../src/lib/engine';
import { IMPACT_TARGETS, assessCohort } from '../src/lib/impact';

const pct = (v: number | null) => (v === null ? '—' : `${Math.round(v)}%`);
const lines = [
  '# Phase 2 impact benchmark',
  '',
  `Generated by \`npm run impact\` from engine \`${MODEL_VERSION}\` and the \`${baseline.id}\` snapshot. The same calculation powers the in-app **Impact scorecard**.`,
  '',
  `Each of the ${employees.length} synthetic workers takes their top-ranked route with the shared foundation prioritised, within their own weekly hours, horizon and budget. These are projections, not observed outcomes: each planned course is assumed to lift its skills to working level (2 of 3), the planner's own rule.`,
  '',
];
for (const scenario of ['moderate', 'rapid'] as const) {
  const c = assessCohort(employees, scenario, baseline);
  lines.push(
    `## ${scenario === 'moderate' ? 'Moderate' : 'Rapid'} AI adoption`,
    '',
    `- **Skill gap distance reduction:** average ${pct(c.averageReduction)} (target ${IMPACT_TARGETS.distanceReduction}%); ${c.reductionMet} of ${c.reductionMeasured} workers reach the target.`,
    `- **Shared foundation in weeks 1–${IMPACT_TARGETS.foundationWeeks}:** average ${pct(c.averageFoundationShare)} (target ${IMPACT_TARGETS.foundationShare}%); ${c.foundationMet} of ${c.foundationMeasured} workers reach the target.`,
    '',
    '| Worker | Route | Gap distance | Reduction | Foundation, weeks 1–4 | Hours | Cost |',
    '| :-- | :-- | --: | --: | --: | --: | --: |',
    ...c.people.map(
      (p) =>
        `| ${p.profile.name} (${p.profile.currentRole}) | ${p.role.shortTitle} | ${p.distanceBefore.toFixed(1)} → ${p.distanceAfter.toFixed(1)} | ${pct(p.reduction)} | ${pct(p.foundation.share)} | ${p.plan.totalHours} | RM${p.plan.totalCost} |`,
    ),
    '',
  );
}
lines.push(
  '## Not yet measured',
  '',
  '- **SME training cost reduction (target 35%):** every catalogue course is currently free, so there is no spend to reduce. A costed comparison is still to be built.',
  '- **Human-confirmed CV skills (target 100%):** enforced in code rather than measured. Extracted skills change a profile only after the user adds and saves them, and RunPod quotes are kept only when they appear word-for-word in the CV text.',
);
console.log(lines.join('\n'));
